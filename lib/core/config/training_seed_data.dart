/// Lightweight data class for seed templates.
class TrainingSeedTemplate {
  final String title;
  final String description;
  final String durationText;

  const TrainingSeedTemplate({
    required this.title,
    required this.description,
    required this.durationText,
  });

  /// Converts to a [TrainingEntity] with default values.
  TrainingEntity toEntity({String? employeeId, String? adminId}) {
    return TrainingEntity(
      id: '', // Will be auto-generated by Firestore
      title: title,
      description: description,
      durationText: durationText,
      status: TrainingStatus.notStarted,
      noExpiration: false,
      employeeId: employeeId,
      adminId: adminId,
    );
  }
}
