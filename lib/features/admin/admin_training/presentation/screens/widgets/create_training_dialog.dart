import 'package:bhmh/core/utils/colors.dart';
import 'package:bhmh/core/widgets/custom_button.dart';
import 'package:bhmh/core/widgets/custom_text_field.dart';
import 'package:bhmh/features/admin/admin_training/data/model/admin_training_model.dart';
import 'package:bhmh/features/admin/admin_training/presentation/provider/admin_training_view_model.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

class CreateTrainingDialog extends ConsumerStatefulWidget {
  final bool isMobile;
  const CreateTrainingDialog({super.key, this.isMobile = false});

  @override
  ConsumerState<CreateTrainingDialog> createState() =>
      _CreateTrainingDialogState();
}

class _CreateTrainingDialogState extends ConsumerState<CreateTrainingDialog> {
  final _formKey = GlobalKey<FormState>();
  final _titleController = TextEditingController();
  final _descController = TextEditingController();
  final _durationController = TextEditingController();

  String _requirementType = 'certificate';
  final List<String> _types = ['certificate', 'acknowledgement'];

  @override
  void dispose() {
    _titleController.dispose();
    _descController.dispose();
    _durationController.dispose();
    super.dispose();
  }

  Future<void> _selectDuration(BuildContext context) async {
    final TimeOfDay? picked = await showTimePicker(
      context: context,
      initialTime: const TimeOfDay(hour: 0, minute: 45),
      helpText: 'SELECT TRAINING DURATION',
      builder: (context, child) {
        return MediaQuery(
          data: MediaQuery.of(context).copyWith(alwaysUse24HourFormat: true),
          child: child!,
        );
      },
    );

    if (picked != null) {
      String formattedDuration = '';
      if (picked.hour > 0) {
        formattedDuration += '${picked.hour}h ';
      }
      if (picked.minute > 0 || picked.hour == 0) {
        formattedDuration += '${picked.minute} mins';
      }
      _durationController.text = formattedDuration.trim();
    }
  }

  Future<void> _handleSubmit() async {
    if (!_formKey.currentState!.validate()) return;

    final newTraining = AdminTrainingModel(
      id: '', // Generated by Firestore
      title: _titleController.text.trim(),
      description: _descController.text.trim(),
      durationText: _durationController.text.trim(),
      requirementType: _requirementType,
      isActive: true,
      createdAt: DateTime.now(),
      updatedAt: DateTime.now(),
    );

    try {
      await ref
          .read(adminTrainingViewModelProvider.notifier)
          .createTraining(newTraining);

      if (mounted) {
        Navigator.of(context).pop();
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Training template published successfully!'),
            backgroundColor: Color(0xFF10B981),
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error: ${e.toString()}'),
            backgroundColor: Colors.redAccent,
          ),
        );
      }
    }
  }

  InputDecoration _inputDecoration(String hint, {Widget? prefixIcon}) {
    return InputDecoration(
      hintText: hint,
      prefixIcon: prefixIcon,
      hintStyle: const TextStyle(fontSize: 14, color: Color(0xFF94A3B8)),
      filled: true,
      fillColor: const Color(0xFFF8FAFC),
      contentPadding: const EdgeInsets.all(16),
      border: OutlineInputBorder(
        borderRadius: BorderRadius.circular(12),
        borderSide: BorderSide(color: Colors.grey.shade200),
      ),
      enabledBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(12),
        borderSide: BorderSide(color: Colors.grey.shade200),
      ),
      focusedBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(12),
        borderSide: const BorderSide(color: AppColors.primaryColor, width: 1.5),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final bool isMobile = widget.isMobile;

    final content = Container(
      width: isMobile ? double.infinity : 550,
      padding: EdgeInsets.all(isMobile ? 20 : 32),
      child: Form(
        key: _formKey,
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              TrainingDialogHeader(isMobile: isMobile),
              const SizedBox(height: 24),

              // Title
              const TrainingInputLabel(text: 'Training Title *'),
              CustomTextField(
                controller: _titleController,
                hintText: 'e.g. HIPAA Compliance 2024',
                prefixIcon: const Icon(
                  Icons.title_rounded,
                  color: Color(0xFF64748B),
                  size: 20,
                ),
                validator: (v) => v!.isEmpty ? 'Title is required' : null,
              ),
              const SizedBox(height: 20),

              // Description
              const TrainingInputLabel(text: 'Description / Summary *'),
              CustomTextField(
                hintText:
                    "Outline the core objectives and curriculum of this module...",
                controller: _descController,
                prefixIcon: const Icon(
                  Icons.notes_rounded,
                  color: Color(0xFF64748B),
                  size: 20,
                ),
                maxLines: 4,
                validator: (v) => v!.isEmpty ? 'Description is required' : null,
              ),
              const SizedBox(height: 20),

              // Duration & Requirement Type
              Row(
                children: [
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        const TrainingInputLabel(text: 'Estimated Duration *'),
                        CustomTextField(
                          hintText: "e.g. 45 mins",
                          controller: _durationController,
                          readOnly: true,
                          onTap: () => _selectDuration(context),
                          prefixIcon: const Icon(
                            Icons.timer_outlined,
                            color: Color(0xFF64748B),
                            size: 20,
                          ),
                          validator: (v) =>
                              v!.isEmpty ? 'Duration is required' : null,
                        ),
                      ],
                    ),
                  ),
                  const SizedBox(width: 16),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        const TrainingInputLabel(text: 'Requirement Type'),
                        DropdownButtonFormField<String>(
                          initialValue: _requirementType,
                          isExpanded: true,
                          decoration: _inputDecoration(
                            '',
                            prefixIcon: const Icon(
                              Icons.verified_user_outlined,
                              color: Color(0xFF64748B),
                              size: 20,
                            ),
                          ),
                          items: _types
                              .map(
                                (t) => DropdownMenuItem(
                                  value: t,
                                  child: Text(
                                    t[0].toUpperCase() + t.substring(1),
                                    style: const TextStyle(
                                      fontSize: 14,
                                      color: Color(0xFF1E293B),
                                    ),
                                    overflow: TextOverflow.ellipsis,
                                  ),
                                ),
                              )
                              .toList(),
                          onChanged: (v) =>
                              setState(() => _requirementType = v!),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 32),

              TrainingDialogFooter(onSubmit: _handleSubmit),
            ],
          ),
        ),
      ),
    );

    if (isMobile) {
      return Padding(
        padding: EdgeInsets.only(
          bottom: MediaQuery.of(context).viewInsets.bottom,
        ),
        child: content,
      );
    }

    return Dialog(
      elevation: 0,
      backgroundColor: Colors.white,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(24)),
      child: content,
    );
  }
}

