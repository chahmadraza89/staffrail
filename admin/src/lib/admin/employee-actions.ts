"use client"

import {
  doc,
  getDoc,
  runTransaction,
  serverTimestamp,
  updateDoc,
  type DocumentData,
  type Firestore,
} from "firebase/firestore"
import { httpsCallable, type Functions } from "firebase/functions"

import { getFirebaseFirestore, getFirebaseFunctions } from "@/lib/firebase/client"
import { FIREBASE_COLLECTIONS } from "@/lib/firebase/collections"
import {
  DEFAULT_CLEARANCES,
  DEFAULT_ONBOARDING_TASKS,
  DEFAULT_TRAININGS,
  clearanceFields,
  onboardingTaskFields,
  trainingFields,
} from "@/lib/admin/seed-templates"

/**
 * Employee lifecycle actions for the Directory — port of
 * lib/features/admin/admin_directory/presentation/provider/admin_directory_actions.dart
 * (registerStaff, updateEmployee, deactivateEmployee only; task review
 * actions arrive with the employee-detail step).
 *
 * Chosen semantics are load-bearing and match the Flutter app:
 *  - registerStaff: the `registerStaff` callable creates the Auth account +
 *    the users/{uid} doc + the welcome notification, and ALSO writes a
 *    minimal legacy subset (2 of the 46 template tasks, the employee's
 *    details/handbook stubs, and one `hipaa_compliance` training). The
 *    client then provisions the FULL Dart template set and RESOLVES the
 *    callable's legacy docs in the same batch, so a web-registered employee
 *    ends up with exactly 46 onboarding tasks + 19 trainings + 4 clearances
 *    (the Flutter flow's joint result today carries 3 extra legacy docs;
 *    legacy docs that already hold real progress are never destroyed).
 *    A setup failure is NEVER a registration failure (the account exists
 *    either way) — it is reported as `setup: "incomplete"` and retried via
 *    completeEmployeeSetup for the SAME uid.
 *  - updateEmployee: merged set of name/email on the user doc (Flutter
 *    writes its fuller DTO merged; same effective fields, fewer risks).
 *    The active-employee check and the update run inside one transaction so
 *    a read-then-write race (employee deactivated mid-edit) cannot bypass
 *    the validation.
 *  - deactivateEmployee: soft delete — isActive:false + deletedAt
 *    (historical relational data must be preserved).
 */

export class EmployeeActionError extends Error {
  constructor(
    message: string,
    readonly code: string,
  ) {
    super(message)
    this.name = "EmployeeActionError"
  }
}

export type SetupStatus = "complete" | "incomplete"

export interface RegisteredStaffResult {
  uid: string
  /** Password-reset URL generated by the callable — shown to the admin once. */
  resetLink: string | null
  /** Whether the client-side document provisioning succeeded. */
  setup: SetupStatus
  /** Present when setup === "incomplete" — actionable message for the UI. */
  setupError?: string
  /** Legacy callable docs kept because they already hold real progress. */
  retainedLegacy?: string[]
}

export interface ProvisionOutcome {
  /** Newly created template documents. */
  created: number
  /** Existing template documents that only received descriptive fields. */
  overlaid: number
  /** Legacy callable defaults removed (pristine only). */
  removed: number
  /** Legacy callable docs kept because they hold employee progress. */
  retainedLegacy: string[]
}

/** Exposed for tests — matches the Flutter callable timeout (45s). */
export const REGISTER_STAFF_TIMEOUT_MS = 45_000

function unwrapCallableError(error: unknown): EmployeeActionError {
  const code = (error as { code?: string })?.code ?? "unknown"
  // Web SDK errors carry "functions/<code>"; fall back to the raw message.
  const rawMessage = ((error as { message?: string })?.message ?? "").replace(
    /^(functions\/|Cloud Firestore: |Firebase: )/,
    "",
  )
  return new EmployeeActionError(rawMessage || "Staff registration failed.", code)
}

/**
 * The `registerStaff` callable's initial-document batch — resolved by the
 * client provisioning below so the joint result has no extra documents.
 * IDs are exactly what functions/src/index.ts writes.
 */
const LEGACY_ONBOARDING_DOC_IDS = ["personal_details", "employee_handbook"] as const
const LEGACY_TRAINING_DOC_IDS = ["hipaa_compliance"] as const

/** Overlays for EXISTING docs touch descriptive/ownership fields ONLY —
 * never status/updatedAt/isCompleted/files/form data, so retries are
 * idempotent and can never clobber employee progress. */
const TASK_OVERLAY_KEYS = ["title", "subtitle", "actionType", "employeeName", "employeeId", "adminId"] as const
const TRAINING_OVERLAY_KEYS = ["title", "description", "durationText", "employeeId", "adminId"] as const
const CLEARANCE_OVERLAY_KEYS = ["title", "description", "employeeName", "employeeId", "adminId"] as const

function pickFields(
  fields: Record<string, unknown>,
  keys: readonly string[],
): Record<string, unknown> {
  const overlay: Record<string, unknown> = {}
  for (const key of keys) {
    overlay[key] = fields[key]
  }
  return overlay
}

/**
 * Pristine legacy docs = untouched defaults that carry zero employee work
 * (the callable writes them those values) — safe to resolve away. Anything
 * with progress (signatures, uploads, form data, completion) is kept.
 */
function isPristineOnboarding(data: DocumentData): boolean {
  return (
    data.status === "notStarted" &&
    data.isCompleted !== true &&
    !data.fileUrl &&
    !data.signatureUrl &&
    !data.formData &&
    !data.completedAt &&
    !data.signedAt &&
    data.adminFormData == null
  )
}

function isPristineTraining(data: DocumentData): boolean {
  return (
    data.status === "notStarted" &&
    !data.certificateUrl &&
    (!Array.isArray(data.certificateUrls) || data.certificateUrls.length === 0) &&
    !data.completedAt &&
    !data.completionDate
  )
}

/**
 * Provisions the full Dart template set for an employee and resolves the
 * callable's legacy defaults — inside ONE transaction, so nothing can erase
 * employee work that lands between the initial read and the commit:
 *
 *  - ALL documents (templates ×3 + legacy subset + the user doc) are read
 *    first (Firestore transactions forbid reads after writes);
 *  - a template is CREATED only if it is still missing at the write
 *    boundary — if another client created it meanwhile, the transaction
 *    conflict re-runs the body and the doc is overlaid instead;
 *  - existing docs receive a description/ownership MERGE only (progress
 *    never overwritten — idempotent, retry-safe);
 *  - a legacy default is DELETED only if it is STILL pristine when the
 *    write commits — a signature that landed mid-flight is retained and
 *    reported;
 *  - every retry re-reads (revalidates) all changed documents, so
 *    signatures, uploads, form data, statuses and timestamps survive.
 *  - on success the SAME transaction stamps `setupStatus: "complete"` on
 *    the user doc (never the reset link — that lives only in the callable
 *    response).
 */
export async function provisionEmployeeDocuments(
  db: Firestore,
  context: { uid: string; name: string; adminId: string },
): Promise<ProvisionOutcome> {
  const seedContext = {
    employeeId: context.uid,
    employeeName: context.name,
    adminId: context.adminId,
  }

  return runTransaction(db, async (transaction) => {
    const assignedAt = new Date()
    const outcome: ProvisionOutcome = { created: 0, overlaid: 0, removed: 0, retainedLegacy: [] }

    // ── Phase 1: read everything before issuing any write ──────────────
    const usersReference = doc(db, FIREBASE_COLLECTIONS.users, context.uid)
    const userSnapshot = await transaction.get(usersReference)
    if (!userSnapshot.exists()) {
      throw new EmployeeActionError("Employee profile not found.", "not-found")
    }

    interface ExistingDoc {
      reference: ReturnType<typeof doc>
      exists: boolean
      data: DocumentData | null
    }
    const readTemplate = async (collectionName: string, id: string): Promise<ExistingDoc> => {
      const reference = doc(db, FIREBASE_COLLECTIONS.users, context.uid, collectionName, id)
      const snapshot = await transaction.get(reference)
      return {
        reference,
        exists: snapshot.exists(),
        data: snapshot.exists() ? (snapshot.data() ?? {}) : null,
      }
    }

    const templateDocs: Array<{ collectionName: string; id: string; doc: ExistingDoc; fields: Record<string, unknown>; overlayKeys: readonly string[] }> = []

    for (const task of DEFAULT_ONBOARDING_TASKS) {
      templateDocs.push({
        collectionName: FIREBASE_COLLECTIONS.onboardingTasks,
        id: task.id,
        doc: await readTemplate(FIREBASE_COLLECTIONS.onboardingTasks, task.id),
        fields: onboardingTaskFields(task, seedContext),
        overlayKeys: TASK_OVERLAY_KEYS,
      })
    }
    for (const training of DEFAULT_TRAININGS) {
      templateDocs.push({
        collectionName: FIREBASE_COLLECTIONS.trainings,
        id: training.id,
        doc: await readTemplate(FIREBASE_COLLECTIONS.trainings, training.id),
        fields: trainingFields(training, seedContext, assignedAt),
        overlayKeys: TRAINING_OVERLAY_KEYS,
      })
    }
    for (const clearance of DEFAULT_CLEARANCES) {
      templateDocs.push({
        collectionName: FIREBASE_COLLECTIONS.clearanceItems,
        id: clearance.id,
        doc: await readTemplate(FIREBASE_COLLECTIONS.clearanceItems, clearance.id),
        fields: clearanceFields(clearance, seedContext),
        overlayKeys: CLEARANCE_OVERLAY_KEYS,
      })
    }

    const legacyDocs: Array<{ doc: ExistingDoc; pristine: (data: DocumentData) => boolean }> = []
    for (const id of LEGACY_ONBOARDING_DOC_IDS) {
      legacyDocs.push({
        doc: await readTemplate(FIREBASE_COLLECTIONS.onboardingTasks, id),
        pristine: isPristineOnboarding,
      })
    }
    for (const id of LEGACY_TRAINING_DOC_IDS) {
      legacyDocs.push({
        doc: await readTemplate(FIREBASE_COLLECTIONS.trainings, id),
        pristine: isPristineTraining,
      })
    }

    // ── Phase 2: writes against the just-read boundary ──────────────────
    for (const entry of templateDocs) {
      if (!entry.doc.exists) {
        transaction.set(entry.doc.reference, {
          ...entry.fields,
          updatedAt: serverTimestamp(),
        })
        outcome.created += 1
      } else {
        transaction.set(
          entry.doc.reference,
          pickFields(entry.fields, entry.overlayKeys),
          { merge: true },
        )
        outcome.overlaid += 1
      }
    }

    // Resolve the callable's legacy subset — deleted only when the doc is
    // STILL pristine at the write boundary; anything with employee work is
    // retained (and reported).
    for (const legacy of legacyDocs) {
      if (!legacy.doc.exists) {
        continue
      }
      if (legacy.pristine(legacy.doc.data ?? {})) {
        transaction.delete(legacy.doc.reference)
        outcome.removed += 1
      } else {
        outcome.retainedLegacy.push(legacy.doc.reference.path.split("/").slice(-2).join("/"))
      }
    }

    // Setup status flips to complete in the same transaction — only after
    // every write above is planned successfully.
    transaction.set(usersReference, { setupStatus: "complete" }, { merge: true })

    return outcome
  })
}

/**
 * Best-effort persistence of the incomplete-setup status so recovery
 * survives closing the dialog, refreshing, or signing in again. Never
 * masks the primary outcome; never stores the reset link.
 */
async function markSetupIncomplete(db: Firestore, uid: string): Promise<void> {
  try {
    await updateDoc(doc(db, FIREBASE_COLLECTIONS.users, uid), {
      setupStatus: "incomplete",
    })
  } catch (error) {
    console.warn("[employee-actions] could not persist the incomplete-setup status:", error)
  }
}

/** Only an admin profile that still exists, is admin, and is active may
 * provision employee documents. */
async function assertActiveAdmin(db: Firestore, adminUid: string): Promise<void> {
  const snapshot = await getDoc(doc(db, FIREBASE_COLLECTIONS.users, adminUid))
  const veto = (() => {
    if (!snapshot.exists()) {
      return "Your admin profile could not be found."
    }
    const data = snapshot.data()
    if (data?.role !== "admin" || data?.isActive === false) {
      return "Only active admins may provision employee setup."
    }
    return null
  })()
  if (veto) {
    throw new EmployeeActionError(veto, "permission-denied")
  }
}

/** Verifies the employee exists AND belongs to the requesting admin. */
async function assertEmployeeOwnership(
  db: Firestore,
  uid: string,
  adminUid: string,
): Promise<DocumentData> {
  const snapshot = await getDoc(doc(db, FIREBASE_COLLECTIONS.users, uid))
  if (!snapshot.exists()) {
    throw new EmployeeActionError("Employee not found", "not-found")
  }
  const data = snapshot.data()
  if (data?.adminId !== adminUid) {
    throw new EmployeeActionError(
      "This employee does not belong to your workspace.",
      "permission-denied",
    )
  }
  return data ?? {}
}

/**
 * Registers a new employee: `registerStaff` callable → provisions templates.
 *
 * A successfully created Auth account is NEVER reported as a failed
 * registration: if provisioning fails the account exists, so the result is
 * `setup: "incomplete"` with the preserved uid + reset link and a
 * retryable path via completeEmployeeSetup.
 *
 * @param adminUid the signed-in admin's uid — stamped on every seeded
 * document (parity: Flutter reads its auth provider for the same value).
 */
export async function registerStaff(
  input: { name: string; email: string; adminUid: string },
  functions?: Functions,
  db?: Firestore,
): Promise<RegisteredStaffResult> {
  const functionsInstance = functions ?? getFirebaseFunctions()
  const firestore = db ?? getFirebaseFirestore()

  let resultUid: string
  let resetLink: string | null = null
  try {
    const callable = httpsCallable<{ email: string; name: string; role: string }, { uid: string; resetLink?: string | null }>(
      functionsInstance,
      "registerStaff",
      { timeout: REGISTER_STAFF_TIMEOUT_MS },
    )
    const result = await callable({
      email: input.email,
      name: input.name,
      role: "employee",
    })
    if (!result.data?.uid) {
      throw new EmployeeActionError("Registration function returned no account id.", "internal")
    }
    resultUid = result.data.uid
    resetLink = result.data.resetLink ?? null
  } catch (error) {
    throw unwrapCallableError(error)
  }

  try {
    await assertActiveAdmin(firestore, input.adminUid)
    const outcome = await provisionEmployeeDocuments(firestore, {
      uid: resultUid,
      name: input.name,
      adminId: input.adminUid,
    })
    return {
      uid: resultUid,
      resetLink,
      setup: "complete",
      ...(outcome.retainedLegacy.length > 0 ? { retainedLegacy: outcome.retainedLegacy } : {}),
    }
  } catch (setupFailure) {
    const setupError =
      setupFailure instanceof EmployeeActionError
        ? setupFailure.message
        : ((setupFailure as { message?: string } | null)?.message ??
          "Employee setup could not be completed.")
    console.warn("[employee-actions] employee document setup warning:", setupFailure)
    // Persist the incomplete status (durable recovery surface), best-effort.
    await markSetupIncomplete(firestore, resultUid)
    return { uid: resultUid, resetLink, setup: "incomplete", setupError }
  }
}

/**
 * Completes document provisioning for an employee whose account already
 * exists (setup was incomplete) — for the SAME uid, without creating
 * another Auth account. Fill-missing + overlay-only semantics make the
 * retry idempotent: completed tasks, signatures, uploads, statuses and
 * progress are preserved. Requires an active admin that owns the employee.
 */
export async function completeEmployeeSetup(
  input: { uid: string; adminUid: string },
  db?: Firestore,
): Promise<ProvisionOutcome> {
  const firestore = db ?? getFirebaseFirestore()
  try {
    await assertActiveAdmin(firestore, input.adminUid)
    const employee = await assertEmployeeOwnership(firestore, input.uid, input.adminUid)
    const name = typeof employee.name === "string" ? employee.name : ""
    return await provisionEmployeeDocuments(firestore, {
      uid: input.uid,
      name,
      adminId: input.adminUid,
    })
  } catch (error) {
    // Persist the incomplete status so recovery stays reachable from the
    // Directory card after a failed retry (best-effort), then surface it.
    if (error instanceof EmployeeActionError && error.code !== "not-found") {
      await markSetupIncomplete(firestore, input.uid)
    }
    throw error
  }
}

/** Updates an existing employee's basic profile (name/email).
 * The validation and the write share one transaction, so an employee
 * deactivated AFTER the dialog opened cannot be edited (no
 * read-then-write race). */
export async function updateEmployee(
  input: { uid: string; name: string; email: string },
  db?: Firestore,
): Promise<void> {
  const firestore = db ?? getFirebaseFirestore()
  try {
    await runTransaction(firestore, async (transaction) => {
      const reference = doc(firestore, FIREBASE_COLLECTIONS.users, input.uid)
      const snapshot = await transaction.get(reference)
      if (!snapshot.exists()) {
        throw new EmployeeActionError("Employee not found", "not-found")
      }
      const data = snapshot.data()
      if (data?.isActive !== true) {
        throw new EmployeeActionError(
          "This employee is deactivated and can no longer be edited.",
          "employee-inactive",
        )
      }
      // Merged set → only name/email change; role/adminId/isActive are
      // never touched from the web panel.
      transaction.update(reference, {
        name: input.name,
        email: input.email,
      })
    })
  } catch (error) {
    if (error instanceof EmployeeActionError) {
      throw error
    }
    const code = (error as { code?: string })?.code ?? "unknown"
    throw new EmployeeActionError("Failed to update employee.", code)
  }
}

/** Soft-deletes an employee (isActive:false + deletedAt; data preserved). */
export async function deactivateEmployee(uid: string, db?: Firestore): Promise<void> {
  const firestore = db ?? getFirebaseFirestore()
  try {
    await updateDoc(doc(firestore, FIREBASE_COLLECTIONS.users, uid), {
      isActive: false,
      deletedAt: serverTimestamp(),
    })
  } catch (error) {
    const code = (error as { code?: string })?.code ?? "unknown"
    throw new EmployeeActionError(
      "Failed to deactivate employee.",
      /permission-denied/.test(code) ? "permission-denied" : code,
    )
  }
}
